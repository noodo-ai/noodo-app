// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { ResourceFilterMenu } from './ResourceFilterMenu'
import { initialFilters } from '../hooks/useResources'
afterEach(cleanup)
it('supports keyboard entry into options, selection, closing and focus restoration', () => {
  const onChange = vi.fn()
  render(<ResourceFilterMenu filters={initialFilters} categories={[]} onChange={onChange} />)
  const trigger = screen.getByRole('button', { name: 'Filter resources' })
  fireEvent.keyDown(trigger, { key: 'ArrowDown' })
  const format = screen.getByRole('menuitem', { name: 'Format' })
  expect(document.activeElement).toBe(format)
  fireEvent.keyDown(format, { key: 'ArrowLeft' })
  const allFormats = screen.getByRole('menuitemradio', { name: 'All formats' })
  expect(document.activeElement).toBe(allFormats)
  fireEvent.keyDown(allFormats, { key: 'ArrowDown' })
  expect(document.activeElement).toBe(screen.getByRole('menuitemradio', { name: 'MD' }))
  fireEvent.click(screen.getByRole('menuitemradio', { name: 'CSV' }))
  expect(onChange).toHaveBeenCalledWith('format', 'csv')
  expect(screen.queryByRole('menu')).toBeNull()
  expect(document.activeElement).toBe(trigger)
})
it('dismisses on Escape, outside pointer and focus leaving the entire cascade', () => {
  render(<><ResourceFilterMenu filters={initialFilters} categories={[]} onChange={vi.fn()} /><button>Outside</button></>)
  const trigger = screen.getByRole('button', { name: 'Filter resources' })
  fireEvent.click(trigger)
  fireEvent.click(screen.getByRole('menuitem', { name: 'Topic' }))
  fireEvent.keyDown(screen.getByRole('menuitemradio', { name: 'Markets' }), { key: 'Escape' })
  expect(screen.queryByRole('menu')).toBeNull()
  expect(document.activeElement).toBe(trigger)
  fireEvent.click(trigger)
  fireEvent.pointerDown(screen.getByRole('button', { name: 'Outside' }))
  expect(screen.queryByRole('menu')).toBeNull()
  fireEvent.click(trigger)
  fireEvent.blur(screen.getByRole('menuitem', { name: 'Format' }), { relatedTarget: screen.getByRole('button', { name: 'Outside' }) })
  expect(screen.queryByRole('menu')).toBeNull()
})
it('exposes personal category options and keeps selections while backing out of the submenu', () => {
  render(<ResourceFilterMenu filters={{ ...initialFilters, scope: 'personal', visibility: 'private', categoryId: 'research' }} categories={[{id:'research',name:'Research notes'}]} onChange={vi.fn()} />)
  fireEvent.click(screen.getByRole('button', { name: 'Filter resources (active)' }))
  const category = screen.getByRole('menuitem', { name: 'Category' })
  fireEvent.click(category)
  const selected = screen.getByRole('menuitemradio', { name: 'Research notes' })
  expect(selected.getAttribute('aria-checked')).toBe('true')
  fireEvent.keyDown(selected, { key: 'ArrowRight' })
  expect(screen.queryByRole('menu', { name: 'Category options' })).toBeNull()
  expect(document.activeElement).toBe(category)
  fireEvent.keyDown(category, { key: 'Escape' })
  fireEvent.click(screen.getByRole('button', { name: 'Filter resources (active)' }))
  fireEvent.click(screen.getByRole('menuitem', { name: 'Category' }))
  expect(screen.getByRole('menuitemradio', { name: 'Research notes' }).getAttribute('aria-checked')).toBe('true')
})
